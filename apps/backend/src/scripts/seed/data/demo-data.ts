export type Weekday = 0 | 1 | 2 | 3 | 4 | 5 | 6; // 0 = pondělí

/**
 * Relativní termín vůči okamžiku seedu:
 * - daysFromNow: za n dní (0 = dnes),
 * - nextWeekday: nejbližší daný den v týdnu (nejbližší sobota / neděle = „tento víkend“),
 * - weekOffset + weekday: daný den v týdnu, offset týdnů od týdne seedu.
 * Pokud by termín vyšel méně než hodinu od seedu nebo do minulosti, posune se o den (resp. týden).
 */
export type DemoSchedule =
  | { daysFromNow: number; time: string }
  | { nextWeekday: Weekday; time: string }
  | { weekOffset: number; weekday: Weekday; time: string };

export type DemoParticipationStatus =
  'pending' | 'approved' | 'rejected' | 'withdrawn' | 'removed';

export interface DemoUser {
  key: string;
  name: string;
  username: string;
  email: string;
  /** Ověřený e-mail (B-011). Neověřený účet ukazuje lištu „Ověř si e-mail“ a nesmí se hlásit na akce. */
  emailVerified: boolean;
  bio: string;
  homeLocalitySlug: DemoLocalitySlug;
  interestSlugs: DemoActivitySlug[];
}

export interface DemoGroup {
  key: string;
  name: string;
  description: string;
  activitySlug: DemoActivitySlug;
  localitySlug: DemoLocalitySlug;
  type: 'public' | 'closed';
  status: 'active' | 'inactive';
  /** Jen u neaktivní skupiny: deactivatedAt = seed − n dní. */
  deactivatedDaysAgo?: number;
  members: {
    userKey: string;
    role: 'admin' | 'member';
    status: 'pending' | 'active' | 'blocked';
    message?: string;
  }[];
}

export interface DemoEvent {
  key: string;
  /** Jen pro čtení a QA: stav akce vyplývající z účastí, do DB se neukládá. */
  scenario: 'chybi' | 'volno' | 'plno' | 'zrusena';
  /** Jen pro čtení: akce připravená pro živou ukázku (viz hlavička souboru). */
  demoCase?: string;
  title: string;
  description?: string;
  activitySlug: DemoActivitySlug;
  schedule: DemoSchedule;
  durationMinutes: number;
  address: string;
  localitySlug: DemoLocalitySlug;
  lat: number;
  lng: number;
  minParticipants: number;
  maxParticipants: number;
  price?: number;
  level?: 'beginner' | 'advanced' | 'all';
  equipment?: string;
  approvalMode: 'approval' | 'open';
  visibility: 'public' | 'private' | 'members';
  organizerKey: string;
  status: 'published' | 'cancelled';
  cancelReason?: string;
  participations: {
    userKey: string;
    status: DemoParticipationStatus;
    message?: string;
  }[];
}

