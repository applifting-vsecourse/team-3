const PRAGUE_TZ = 'Europe/Prague';
/** Akce nesmí začít dřív než hodinu po seedu, jinak se posune. */
const MIN_LEAD_MS = 60 * 60000;

/** Posun časové zóny Prahy vůči UTC v minutách pro daný okamžik (řeší letní/zimní čas). */
const pragueOffsetMinutes = (date: Date): number => {
  const parts = new Intl.DateTimeFormat('en-US', {
    timeZone: PRAGUE_TZ,
    // hour12 místo hourCycle: backend kompiluje s lib ES2017, kde hourCycle v typech chybí
    hour12: false,
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
    hour: '2-digit',
    minute: '2-digit',
  }).formatToParts(date);
  const get = (type: string): number =>
    Number(parts.find((p) => p.type === type)?.value);
  // některé prostředí vrací při hour12: false o půlnoci „24“
  const asUtc = Date.UTC(
    get('year'),
    get('month') - 1,
    get('day'),
    get('hour') % 24,
    get('minute'),
  );
  return Math.round((asUtc - date.getTime()) / 60000);
};

/** Pražské datum (kalendářní den) okamžiku `now`. */
const pragueDate = (
  now: Date,
): { y: number; m: number; d: number; weekday: number } => {
  const local = new Date(now.getTime() + pragueOffsetMinutes(now) * 60000);
  return {
    y: local.getUTCFullYear(),
    m: local.getUTCMonth(),
    d: local.getUTCDate(),
    weekday: (local.getUTCDay() + 6) % 7, // 0 = pondělí
  };
};

/** Převede pražský místní čas na Date (UTC okamžik). */
const fromPragueLocal = (
  y: number,
  m: number,
  d: number,
  hh: number,
  mm: number,
): Date => {
  const guess = new Date(Date.UTC(y, m, d, hh, mm));
  const offset = pragueOffsetMinutes(guess);
  const result = new Date(guess.getTime() - offset * 60000);
  // korekce v okolí přechodu času
  const offset2 = pragueOffsetMinutes(result);
  return offset2 === offset
    ? result
    : new Date(guess.getTime() - offset2 * 60000);
};

/** Začátek akce vůči okamžiku seedu. Výsledek je vždy aspoň hodinu v budoucnosti. */
export const resolveStartsAt = (
  schedule: DemoSchedule,
  now: Date = new Date(),
): Date => {
  const [hh, mm] = schedule.time.split(':').map(Number);
  const today = pragueDate(now);
  let shift: number;
  let step: number;
  if ('daysFromNow' in schedule) {
    shift = schedule.daysFromNow;
    step = 1;
  } else if ('nextWeekday' in schedule) {
    shift = (schedule.nextWeekday - today.weekday + 7) % 7;
    step = 7;
  } else {
    shift = schedule.weekOffset * 7 + schedule.weekday - today.weekday;
    step = 7;
  }
  let start = fromPragueLocal(today.y, today.m, today.d + shift, hh, mm);
  while (start.getTime() < now.getTime() + MIN_LEAD_MS) {
    shift += step;
    start = fromPragueLocal(today.y, today.m, today.d + shift, hh, mm);
  }
  return start;
};

export const resolveEndsAt = (event: DemoEvent, now: Date = new Date()): Date =>
  new Date(
    resolveStartsAt(event.schedule, now).getTime() +
      event.durationMinutes * 60000,
  );
